// retrier-report replays the polling backoff behaviour on a deterministic
// virtual clock and writes reviewable evidence: a JSON event trace and a
// Markdown report with the request-count curve per fixed time window.
//
// Run with:
//
//	go run -tags retrier_report ./cmd/retrier-report
package main

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	apierrors "k8s.io/apimachinery/pkg/api/errors"

	"github.com/fluxcd/flux2/v2/internal/retrier"
)

const (
	outDir    = "artifacts/retrier"
	window    = 30 * time.Second
	scenarioN = 300 * time.Second
)

type scenario struct {
	name      string
	condition func(attempt int) (bool, error)
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "retrier-report failed: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	transient := apierrors.NewServiceUnavailable("kube-apiserver unavailable")
	internal := apierrors.NewInternalError(errors.New("etcd quorum lost"))
	rateLimited := apierrors.NewTooManyRequests("API rate limit exceeded", 45)

	scenarios := []scenario{
		{
			name: "01-sustained-failure",
			condition: func(int) (bool, error) {
				return false, transient
			},
		},
		{
			name: "02-rate-limit-retry-after",
			condition: func(int) (bool, error) {
				return false, rateLimited
			},
		},
		{
			// Four failures, then the API recovers while the resource stays
			// in progress, then the resource becomes ready: self-healing.
			name: "03-recovery-convergence",
			condition: func(attempt int) (bool, error) {
				switch {
				case attempt < 4:
					return false, internal
				case attempt < 7:
					return false, nil
				default:
					return true, nil
				}
			},
		},
	}

	var report strings.Builder
	report.WriteString("# Retrier backoff evidence\n\n")
	report.WriteString(fmt.Sprintf("Generated by `go run -tags retrier_report ./cmd/retrier-report` using a deterministic virtual clock (jitter disabled, window %s).\n\n", window))
	report.WriteString("Config: initial interval 2s, factor 2.0, max interval 60s, max rate-limit wait 5m.\n\n")

	for _, sc := range scenarios {
		events, err := replay(sc)
		if err != nil {
			return fmt.Errorf("scenario %s: %w", sc.name, err)
		}
		if err := writeTrace(sc.name, events); err != nil {
			return err
		}
		writeScenarioSection(&report, sc.name, events)
	}

	reportPath := filepath.Join(outDir, "report.md")
	if err := os.WriteFile(reportPath, []byte(report.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s and %s/*.json\n", reportPath, outDir)
	return nil
}

func replay(sc scenario) ([]retrier.Event, error) {
	cfg := retrier.DefaultConfig()
	cfg.JitterFactor = 0

	var events []retrier.Event
	poller, err := retrier.NewReportPoller(cfg, scenarioN, func(ev retrier.Event) {
		events = append(events, ev)
	})
	if err != nil {
		return nil, err
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	attempt := 0
	err = poller.PollUntil(ctx, func(context.Context) (bool, error) {
		done, condErr := sc.condition(attempt)
		attempt++
		return done, condErr
	})
	// DeadlineExceeded is the expected termination of the failure scenarios.
	if err != nil && !errors.Is(err, context.DeadlineExceeded) {
		return nil, err
	}
	return events, nil
}

func writeTrace(name string, events []retrier.Event) error {
	type traceEvent struct {
		Attempt int             `json:"attempt"`
		Elapsed string          `json:"elapsed"`
		Outcome retrier.Outcome `json:"outcome"`
		Wait    string          `json:"wait"`
		Err     string          `json:"err,omitempty"`
	}
	trace := make([]traceEvent, 0, len(events))
	for _, ev := range events {
		trace = append(trace, traceEvent{
			Attempt: ev.Attempt,
			Elapsed: ev.Elapsed.String(),
			Outcome: ev.Outcome,
			Wait:    ev.Wait.String(),
			Err:     ev.Err,
		})
	}
	data, err := json.MarshalIndent(trace, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, name+".trace.json"), append(data, '\n'), 0o644)
}

func writeScenarioSection(b *strings.Builder, name string, events []retrier.Event) {
	b.WriteString("## " + name + "\n\n")
	b.WriteString(fmt.Sprintf("Total requests: **%d** over %s.\n\n", len(events), scenarioN))

	b.WriteString("Requests per " + window.String() + " window (request volume curve):\n\n")
	b.WriteString("```\n")
	maxCount := 1
	buckets := bucketize(events)
	// Baseline: the previous fixed 2s poll interval made the same number of
	// requests in every window regardless of the failures it was receiving.
	baselinePerWindow := int(window / retrier.DefaultInitialInterval)
	for _, count := range buckets {
		if count > maxCount {
			maxCount = count
		}
	}
	for i, count := range buckets {
		from := time.Duration(i) * window
		to := from + window
		bar := strings.Repeat("#", count)
		b.WriteString(fmt.Sprintf("%3s-%-3s new=%2d %-12s (old fixed 2s poll=%d)\n",
			from, to, count, bar, baselinePerWindow))
	}
	b.WriteString("```\n\n")

	b.WriteString("Schedule (first 12 requests):\n\n")
	b.WriteString("| # | elapsed | outcome | next wait |\n")
	b.WriteString("|---|---------|---------|-----------|\n")
	limit := 12
	if len(events) < limit {
		limit = len(events)
	}
	for _, ev := range events[:limit] {
		b.WriteString(fmt.Sprintf("| %d | %s | %s | %s |\n", ev.Attempt, ev.Elapsed, ev.Outcome, ev.Wait))
	}
	b.WriteString("\n")

	if name == "03-recovery-convergence" {
		last := events[len(events)-1]
		b.WriteString(fmt.Sprintf("Convergence: final outcome is `%s` at %s after %d requests.\n\n",
			last.Outcome, last.Elapsed, len(events)))
	}
}

func bucketize(events []retrier.Event) []int {
	buckets := make([]int, int(scenarioN/window))
	for _, ev := range events {
		idx := int(ev.Elapsed / window)
		if idx >= len(buckets) {
			idx = len(buckets) - 1
		}
		buckets[idx]++
	}
	return buckets
}
